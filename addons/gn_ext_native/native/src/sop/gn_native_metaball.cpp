// ═══════════════════════════════════════════════════════════════════════════════
// Implicit field evaluation
// ═══════════════════════════════════════════════════════════════════════════════

float GNNativeMetaball::_eval_field(const Vector3 &p,
                                    const Vector3 *balls, const float *radii, int count) {
    float val = 0.0f;
    for (int i = 0; i < count; ++i) {
        Vector3 diff = p - balls[i];
        float dist_sq = diff.dot(diff);
        float r = radii[i];
        if (dist_sq > 0.0001f) {
            val += (r * r) / dist_sq;
        } else {
            val += 10000.0f;
        }
    }
    return val;
}

Vector3 GNNativeMetaball::_compute_normal(const Vector3 &p,
                                          const Vector3 *balls, const float *radii, int count) {
    // Gradient of Σ(r²/|p-c|²):  d/dp = -2r²(p-c)/|p-c|^4
    Vector3 grad(0, 0, 0);
    for (int i = 0; i < count; ++i) {
        Vector3 diff = p - balls[i];
        float dist_sq = diff.dot(diff);
        if (dist_sq < 0.0001f) {
            continue;
        }
        float r = radii[i];
        grad += diff * (-2.0f * r * r / (dist_sq * dist_sq));
    }
    float len = grad.length();
    if (len > 0.0001f) {
        return -grad / len;  // Negate: gradient points inward, normal outward
    }
    return Vector3(0, 1, 0);
}

// ═══════════════════════════════════════════════════════════════════════════════
// Main processing — voxel grid evaluation + marching cubes extraction
// ═══════════════════════════════════════════════════════════════════════════════

Dictionary GNNativeMetaball::process(const PackedVector3Array &ball_positions,
                                     const PackedFloat32Array &ball_radii,
                                     int resolution, double bounds_size, double threshold) {
    Dictionary result;
    PackedVector3Array out_positions;
    PackedVector3Array out_normals;

    int ball_count = ball_positions.size();
    if (ball_count == 0 || ball_radii.size() < ball_count) {
        result["positions"] = out_positions;
        result["normals"] = out_normals;
        return result;
    }

    resolution = CLAMP(resolution, 4, 128);
    float half_bounds = static_cast<float>(bounds_size) * 0.5f;
    float thresh = static_cast<float>(threshold);

    const Vector3 *balls_ptr = ball_positions.ptr();
    const float *radii_ptr = ball_radii.ptr();

    int grid_size = resolution + 1;
    float cell_size = (half_bounds * 2.0f) / static_cast<float>(resolution);

    // ── Evaluate scalar field on 3D grid ──
    int total_voxels = grid_size * grid_size * grid_size;
    float *field = new float[total_voxels];

    for (int iz = 0; iz < grid_size; ++iz) {
        for (int iy = 0; iy < grid_size; ++iy) {
            for (int ix = 0; ix < grid_size; ++ix) {
                Vector3 p(-half_bounds + ix * cell_size,
                          -half_bounds + iy * cell_size,
                          -half_bounds + iz * cell_size);
                field[iz * grid_size * grid_size + iy * grid_size + ix] =
                    _eval_field(p, balls_ptr, radii_ptr, ball_count);
            }
        }
    }

    // ── Marching cubes: iterate over cells ──
    // Pre-reserve a rough estimate to reduce re-allocations
    int estimated_tris = resolution * resolution * 2;
    out_positions.resize(0);
    out_normals.resize(0);

    Vector3 edge_verts[12];

    for (int iz = 0; iz < resolution; ++iz) {
        for (int iy = 0; iy < resolution; ++iy) {
            for (int ix = 0; ix < resolution; ++ix) {

                // Build cube index from 8 corner values
                float corner_vals[8];
                Vector3 corner_pos[8];
                int cube_idx = 0;

                for (int ci = 0; ci < 8; ++ci) {
                    int ox = ix + CORNER_OFFSETS[ci][0];
                    int oy = iy + CORNER_OFFSETS[ci][1];
                    int oz = iz + CORNER_OFFSETS[ci][2];

                    corner_pos[ci] = Vector3(
                        -half_bounds + ox * cell_size,
                        -half_bounds + oy * cell_size,
                        -half_bounds + oz * cell_size);
                    corner_vals[ci] = field[oz * grid_size * grid_size + oy * grid_size + ox];

                    if (corner_vals[ci] >= thresh) {
                        cube_idx |= (1 << ci);
                    }
                }

                // Skip empty or fully inside cells
                if (cube_idx == 0 || cube_idx == 255) {
                    continue;
                }

                // Interpolate edge vertices
                int edge_flags = EDGE_TABLE[cube_idx];
                for (int ei = 0; ei < 12; ++ei) {
                    if (!(edge_flags & (1 << ei))) {
                        continue;
                    }
                    int v0 = EDGE_CONN[ei][0];
                    int v1 = EDGE_CONN[ei][1];
                    float denom = corner_vals[v1] - corner_vals[v0];
                    float t = (denom != 0.0f)
                        ? (thresh - corner_vals[v0]) / denom
                        : 0.5f;
                    t = CLAMP(t, 0.0f, 1.0f);
                    edge_verts[ei] = corner_pos[v0].lerp(corner_pos[v1], t);
                }

                // Emit triangles
                const int *tri_row = TRI_TABLE[cube_idx];
                for (int ti = 0; tri_row[ti] != -1; ti += 3) {
                    Vector3 v0 = edge_verts[tri_row[ti]];
                    Vector3 v1 = edge_verts[tri_row[ti + 1]];
                    Vector3 v2 = edge_verts[tri_row[ti + 2]];

                    out_positions.push_back(v0);
                    out_positions.push_back(v1);
                    out_positions.push_back(v2);

                    out_normals.push_back(_compute_normal(v0, balls_ptr, radii_ptr, ball_count));
                    out_normals.push_back(_compute_normal(v1, balls_ptr, radii_ptr, ball_count));
                    out_normals.push_back(_compute_normal(v2, balls_ptr, radii_ptr, ball_count));
                }
            }
        }
    }

    delete[] field;

    result["positions"] = out_positions;
    result["normals"] = out_normals;
    return result;
}
